from datetime import datetime, timezone

from sqlalchemy import (
    DateTime,
    ForeignKey,
    Integer,
    JSON,
    String,
    Text,
)

from sqlalchemy.orm import Mapped, mapped_column

from app.database.connection import Base


class ScannerFindingModel(Base):
    """
    Stores security findings generated by an MCP scanner.
    """

    __tablename__ = "scanner_findings"

    id: Mapped[int] = mapped_column(
        Integer,
        primary_key=True,
        index=True,
    )

    finding_id: Mapped[str] = mapped_column(
        String(100),
        nullable=False,
        index=True,
    )

    source: Mapped[str] = mapped_column(String(100))

    target: Mapped[str] = mapped_column(String(200))

    tool_name: Mapped[str | None] = mapped_column(
        String(200),
        nullable=True,
    )

    category: Mapped[str] = mapped_column(String(100))

    title: Mapped[str] = mapped_column(String(200))

    description: Mapped[str] = mapped_column(Text)

    scanner_severity: Mapped[str | None] = mapped_column(
        String(20),
        nullable=True,
    )

    evidence: Mapped[list] = mapped_column(
        JSON,
        default=list,
        nullable=False,
    )

    created_at: Mapped[datetime] = mapped_column(
        DateTime(timezone=True),
        default=lambda: datetime.now(timezone.utc),
    )


class ScannerAIAnalysisModel(Base):
    """
    Stores Gemini analyses associated with MCP findings.
    """

    __tablename__ = "scanner_ai_analyses"

    id: Mapped[int] = mapped_column(
        Integer,
        primary_key=True,
    )

    finding_db_id: Mapped[int] = mapped_column(
        ForeignKey("scanner_findings.id"),
        nullable=False,
        index=True,
    )

    status: Mapped[str] = mapped_column(
        String(20),
        default="pending",
        nullable=False,
    )

    event_description: Mapped[str | None] = mapped_column(
        Text,
        nullable=True,
    )

    threat_type: Mapped[str | None] = mapped_column(
        String(200),
        nullable=True,
    )

    ai_severity: Mapped[str | None] = mapped_column(
        String(20),
        nullable=True,
    )

    summary: Mapped[str | None] = mapped_column(
        Text,
        nullable=True,
    )

    recommended_actions: Mapped[list] = mapped_column(
        JSON,
        default=list,
        nullable=False,
    )

    created_at: Mapped[datetime] = mapped_column(
        DateTime(timezone=True),
        default=lambda: datetime.now(timezone.utc),
    )
    